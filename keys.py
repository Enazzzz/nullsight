"""Windows virtual-key codes for NULLSIGHT input.

Hyperlite only exposes a handful of named keys; we define the rest here and
pass integer VK codes directly to ``engine.key_down``.
"""

# Movement
W = 0x57
A = 0x41
S = 0x53
D = 0x44
Q = 0x51
E = 0x45
R = 0x52
G = 0x47
X = 0x58
Z = 0x5A

# Digits (top row)
D0 = 0x30
D1 = 0x31
D2 = 0x32
D3 = 0x33
D4 = 0x34
D5 = 0x35
D6 = 0x36
D7 = 0x37
D8 = 0x38
D9 = 0x39

# Actions
SPACE = 0x20
TAB = 0x09
RETURN = 0x0D
ESCAPE = 0x1B
SHIFT = 0x10
CONTROL = 0x11
DELETE = 0x2E
F1 = 0x70
F11 = 0x7A

# OEM: [ ] - =
OEM4 = 0xDB  # [
OEM6 = 0xDD  # ]
OEM_MINUS = 0xBD
OEM_PLUS = 0xBB

# Arrow keys (look fallback when the cursor is not captured)
LEFT = 0x25
UP = 0x26
RIGHT = 0x27
DOWN = 0x28
